import type { ErdDiagram, ErdTable } from "./types";
import { newColumn, newId, type ErdColumn } from "./types";
import type { SchemaTable } from "@/lib/sql/types";

/**
 * Diagram ⇄ DDL.
 *
 * Generating SQL from the diagram is a direct walk of the model. Going the
 * other way is the interesting half — and it does **not** contain a SQL parser.
 * Instead `importFromSchema` consumes the introspection output of a real
 * Postgres that has already executed the DDL (see `useSqlEngine`), so any
 * statement Postgres accepts is imported with perfect fidelity: no dialect
 * gaps, no half-supported syntax, no parser to maintain.
 */

/* ------------------------------------------------------------- generate */

/** Quotes an identifier only when it actually needs it. */
function ident(name: string): string {
  return /^[a-z_][a-z0-9_]*$/.test(name) ? name : `"${name.replace(/"/g, '""')}"`;
}

function columnLine(column: ErdColumn, padTo: number): string {
  const parts = [ident(column.name).padEnd(padTo), column.type];

  if (column.isPrimaryKey) parts.push("PRIMARY KEY");
  else {
    if (!column.isNullable) parts.push("NOT NULL");
    if (column.isUnique) parts.push("UNIQUE");
  }
  if (column.defaultValue) parts.push(`DEFAULT ${column.defaultValue}`);

  return `  ${parts.join(" ").trimEnd()}`;
}

/**
 * Emits `CREATE TABLE` statements followed by the foreign keys as `ALTER
 * TABLE`. Splitting them means the script runs regardless of table order and
 * survives circular references — the usual reason a generated schema won't
 * execute top to bottom.
 */
export function toDdl(diagram: ErdDiagram): string {
  if (diagram.tables.length === 0) {
    return "-- Add a table to start generating DDL.";
  }

  const tableName = (id: string) =>
    diagram.tables.find((t) => t.id === id)?.name ?? "unknown_table";
  const columnName = (tableId: string, columnId: string) =>
    diagram.tables
      .find((t) => t.id === tableId)
      ?.columns.find((c) => c.id === columnId)?.name ?? "id";

  const creates = diagram.tables.map((table) => {
    const pad = Math.max(...table.columns.map((c) => ident(c.name).length), 4);
    const body = table.columns.map((c) => columnLine(c, pad)).join(",\n");
    const comment = table.note ? `-- ${table.note}\n` : "";
    return `${comment}CREATE TABLE ${ident(table.name)} (\n${body}\n);`;
  });

  const alters: string[] = [];
  for (const table of diagram.tables) {
    for (const column of table.columns) {
      if (!column.references) continue;
      if (!diagram.tables.some((t) => t.id === column.references!.tableId)) continue;

      const onDelete = column.onDelete
        ? ` ON DELETE ${column.onDelete.toUpperCase()}`
        : "";
      alters.push(
        `ALTER TABLE ${ident(table.name)}\n` +
          `  ADD CONSTRAINT ${ident(`${table.name}_${column.name}_fkey`)}\n` +
          `  FOREIGN KEY (${ident(column.name)})\n` +
          `  REFERENCES ${ident(tableName(column.references.tableId))} ` +
          `(${ident(columnName(column.references.tableId, column.references.columnId))})` +
          `${onDelete};`,
      );
    }
  }

  const header = `-- ${diagram.name}\n-- Generated by SQLQuest · ${diagram.tables.length} table${diagram.tables.length === 1 ? "" : "s"}\n`;
  return [header, creates.join("\n\n"), alters.length ? `\n${alters.join("\n\n")}` : ""]
    .filter(Boolean)
    .join("\n")
    .trimEnd();
}

/* --------------------------------------------------------------- import */

/** Lays tables out on a loose grid; the learner rearranges from there. */
function gridPosition(index: number): { x: number; y: number } {
  const perRow = 3;
  return {
    x: 60 + (index % perRow) * 360,
    y: 60 + Math.floor(index / perRow) * 320,
  };
}

/**
 * Builds a diagram from live `information_schema` output.
 *
 * Two passes: create every table first so foreign keys always have a target to
 * resolve, then wire the references by name.
 */
export function importFromSchema(
  schema: SchemaTable[],
  name = "Imported schema",
): ErdDiagram {
  const tables: ErdTable[] = schema.map((table, i) => ({
    id: newId("t"),
    name: table.name,
    position: gridPosition(i),
    columns: table.columns.map((c) =>
      newColumn({
        name: c.name,
        type: normaliseType(c.type),
        isPrimaryKey: c.isPrimaryKey,
        isNullable: c.nullable,
        isUnique: false,
      }),
    ),
  }));

  const byName = new Map(tables.map((t) => [t.name, t]));

  schema.forEach((sourceTable, ti) => {
    sourceTable.columns.forEach((sourceColumn, ci) => {
      if (!sourceColumn.references) return;

      const targetTable = byName.get(sourceColumn.references.table);
      if (!targetTable) return;
      const targetColumn = targetTable.columns.find(
        (c) => c.name === sourceColumn.references!.column,
      );
      if (!targetColumn) return;

      tables[ti].columns[ci].references = {
        tableId: targetTable.id,
        columnId: targetColumn.id,
      };
    });
  });

  return {
    id: newId("d"),
    name,
    kind: "erd",
    tables,
    updatedAt: new Date().toISOString(),
  };
}

/** Postgres reports verbose type names; shorten them for display. */
function normaliseType(type: string): string {
  return type
    .replace("character varying", "varchar")
    .replace("timestamp without time zone", "timestamp")
    .replace("timestamp with time zone", "timestamptz")
    .replace("double precision", "float8")
    .replace("boolean", "boolean")
    .replace("integer", "integer");
}

/* ---------------------------------------------------------------- misc */

export function diagramToJson(diagram: ErdDiagram): string {
  return JSON.stringify(diagram, null, 2);
}

export function diagramFromJson(raw: string): ErdDiagram {
  const parsed = JSON.parse(raw) as ErdDiagram;
  if (!Array.isArray(parsed.tables)) {
    throw new Error("That file doesn't contain a diagram.");
  }
  return parsed;
}

/** Quick structural summary, shown in the toolbar. */
export function diagramStats(diagram: ErdDiagram) {
  const columns = diagram.tables.reduce((n, t) => n + t.columns.length, 0);
  const keys = diagram.tables.reduce(
    (n, t) => n + t.columns.filter((c) => c.references).length,
    0,
  );
  return { tables: diagram.tables.length, columns, relationships: keys };
}
